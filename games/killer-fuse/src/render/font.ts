export type FontName = "small" | "big";

export interface FontDef {
  readonly glyphs: Readonly<Record<string, readonly string[]>>;
  readonly width: number;
  readonly height: number;
}

export const FONTS: Readonly<Record<FontName, FontDef>> = {
  small: { glyphs: SMALL, width: 3, height: 5 },
  big: { glyphs: BIG, width: 5, height: 7 },
};

/** Pixels a string takes: glyphs a pixel apart, a space as wide as a glyph. Unknown characters count as spaces. */
export function textWidth(text: string, font: FontName = "small"): number {
  const length = [...text].length;
  return length === 0 ? 0 : length * (FONTS[font].width + 1) - 1;
}

export interface TextPixel {
  readonly x: number;
  readonly y: number;
}

/** Lit pixels of `text` with its top-left corner at the origin. */
export function layoutText(
  text: string,
  font: FontName = "small",
): TextPixel[] {
  const def = FONTS[font];
  const pixels: TextPixel[] = [];
  [...text].forEach((char, index) => {
    const glyph = def.glyphs[char];
    if (!glyph) return;
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x += 1)
        if (row[x] === "#") pixels.push({ x: index * (def.width + 1) + x, y });
    });
  });
  return pixels;
}
