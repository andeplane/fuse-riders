/**
 * ChartNet charts for the game: the learned model's rhythm (`games/fusemania/charts/chartnet/placement.json`, written
 * by `gen.py placement`) with the rule generator's arrows, jumps, freezes and mines.
 *
 *   pnpm exec tsx scripts/chartnet/hybrid.ts
 *
 * Writes `games/fusemania/charts/chartnet/<id>.ssc` (each song's header and timing with its four ChartNet charts) and
 * bundles their charts into `games/fusemania/src/engine/chartnet-data.ts`, which the game offers after the song's own.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { parseAnalysis } from "../lib/fusemania/analysis.js";
import { generateCharts, type Difficulty } from "../lib/fusemania/generate.js";
import { SONGS } from "../lib/fusemania/songs.js";
import { noteData } from "../lib/fusemania/ssc.js";

process.chdir(fileURLToPath(new URL("../..", import.meta.url)));
const CHARTS = "games/fusemania/charts";
const BUNDLE = "games/fusemania/src/engine/chartnet-data.ts";

/** The description that marks a chart as ChartNet's, which the game's library shows and sorts by. */
export const CHARTNET = "ChartNet";

const placement = JSON.parse(
  readFileSync(`${CHARTS}/chartnet/placement.json`, "utf8"),
) as Record<string, Partial<Record<Difficulty, number[]>>>;

const bundled: Record<string, string> = {};
for (const song of SONGS) {
  const beats = placement[song.id];
  if (!beats) continue;
  const analysis = parseAnalysis(
    readFileSync(`${CHARTS}/analysis/${song.id}.json`, "utf8"),
  );
  const own = readFileSync(`${CHARTS}/${song.id}.ssc`, "utf8");
  const head = own.slice(0, own.indexOf("\n#NOTEDATA:"));
  const blocks = generateCharts(analysis, beats)
    .map((chart) =>
      [
        "",
        "#NOTEDATA:;",
        "#STEPSTYPE:dance-single;",
        `#DESCRIPTION:${CHARTNET};`,
        `#DIFFICULTY:${chart.difficulty};`,
        `#METER:${chart.meter};`,
        `#CREDIT:${CHARTNET};`,
        `#NOTES:\n${noteData(chart, analysis.slotsPerBeat)}\n;`,
      ].join("\n"),
    )
    .join("\n");
  writeFileSync(`${CHARTS}/chartnet/${song.id}.ssc`, `${head}\n${blocks}\n`);
  bundled[song.id] = `${blocks}\n`;
  console.log(`charted ${song.id}`);
}

const module = [
  "// Generated by scripts/chartnet/hybrid.ts from games/fusemania/charts/chartnet/*.ssc. Do not edit.",
  "",
  "/** Per song id, extra `.ssc` charts (ChartNet's) to append to the song's own simfile. */",
  `export const CHARTNET_DATA: Readonly<Record<string, string>> = ${JSON.stringify(bundled)};`,
  "",
].join("\n");
writeFileSync(BUNDLE, await format(module, { parser: "typescript" }));
console.log(`bundled ${Object.keys(bundled).length} songs into ${BUNDLE}`);
