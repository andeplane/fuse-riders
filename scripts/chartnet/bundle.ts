/**
 * ChartNet charts into the game: each song's ChartNet `.ssc` (written by `gen2.py fuse` to
 * `$CHARTNET_WORK/out_fuse2`) gets the song's own header and timing and goes to
 * `games/fusemania/charts/chartnet/<id>.ssc`; their charts are bundled into
 * `games/fusemania/src/engine/chartnet-data.ts`, which the game offers after the song's own charts.
 *
 *   pnpm exec tsx scripts/chartnet/bundle.ts [generated dir]
 *
 * With no directory it only re-bundles the `.ssc` files already in the repository.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { SONGS } from "../lib/fusemania/songs.js";

const [generated] = process.argv.slice(2);
process.chdir(fileURLToPath(new URL("../..", import.meta.url)));
const CHARTS = "games/fusemania/charts";
const BUNDLE = "games/fusemania/src/engine/chartnet-data.ts";

/** Everything from the first chart on. */
const chartsOf = (ssc: string): string =>
  ssc.slice(ssc.indexOf("\n#NOTEDATA:"));

const bundled: Record<string, string> = {};
for (const song of SONGS) {
  const target = join(CHARTS, "chartnet", `${song.id}.ssc`);
  if (generated) {
    const own = readFileSync(join(CHARTS, `${song.id}.ssc`), "utf8");
    const head = own.slice(0, own.indexOf("\n#NOTEDATA:"));
    const charts = chartsOf(
      readFileSync(join(generated, `${song.id}.ssc`), "utf8"),
    ).trimEnd();
    writeFileSync(target, `${head}\n${charts}\n`);
  }
  bundled[song.id] = `${chartsOf(readFileSync(target, "utf8")).trimEnd()}\n`;
}

const module = [
  "// Generated by scripts/chartnet/bundle.ts from games/fusemania/charts/chartnet/*.ssc. Do not edit.",
  "",
  "/** Per song id, extra `.ssc` charts (ChartNet's) to append to the song's own simfile. */",
  `export const CHARTNET_DATA: Readonly<Record<string, string>> = ${JSON.stringify(bundled)};`,
  "",
].join("\n");
writeFileSync(BUNDLE, await format(module, { parser: "typescript" }));
console.log(`bundled ${Object.keys(bundled).length} songs into ${BUNDLE}`);
