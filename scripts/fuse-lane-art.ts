/**
 * Writes Fuse Lane's art manifest and prompt sheet from `games/fuse-lane/art/assets.ts`, the one table the page also
 * loads its images from: `pnpm exec tsx scripts/fuse-lane-art.ts` (or `--check` to fail when they are out of date).
 * The PNGs themselves are generated elsewhere and dropped into `public/` at each asset's `file` path.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { ART, STYLE } from "../games/fuse-lane/art/assets.ts";

const dir = fileURLToPath(new URL("../games/fuse-lane/art/", import.meta.url));

const manifest =
  JSON.stringify(
    {
      style: STYLE,
      root: "public/",
      assets: ART.map(
        ({ id, file, width, height, anchor, transparent, frames, prompt }) => ({
          id,
          file,
          width,
          height,
          anchor,
          transparent,
          ...(frames ? { frames } : {}),
          prompt,
        }),
      ),
    },
    null,
    2,
  ) + "\n";

const groups: [string, string][] = [
  ["board-", "Board"],
  ["building-", "Buildings"],
  ["avatar-", "Characters"],
  ["keeper-", "Shopkeepers"],
  ["icon-", "Item icons"],
  ["ui-", "UI icons"],
];
const sheet = [
  "# Fuse Lane art prompts",
  "",
  "Generated by `scripts/fuse-lane-art.ts` from `art/assets.ts`; edit the table, not this file.",
  "",
  "Every image is a PNG saved at `public/<file>` (the page serves `public/` from the site base) at exactly the canvas size given. The anchor is the point the game places at the asset's position, as fractions of width and height from the top left. The page draws a coloured placeholder for any file that is missing, so assets can land one at a time.",
  "",
  "## Shared style reference",
  "",
  "Append this to every prompt:",
  "",
  `> ${STYLE}`,
  "",
  ...groups.flatMap(([prefix, title]) => [
    `## ${title}`,
    "",
    ...ART.filter((asset) => asset.id.startsWith(prefix)).flatMap((asset) => [
      `### \`${asset.id}\``,
      "",
      `- File: \`public/${asset.file}\``,
      `- Canvas: ${asset.width} × ${asset.height} px${asset.frames ? `, ${asset.frames} frames of ${asset.width / asset.frames} × ${asset.height} left to right` : ""}`,
      `- Anchor: (${asset.anchor[0]}, ${asset.anchor[1]})`,
      `- Background: ${asset.transparent ? "transparent" : "opaque"}`,
      "",
      asset.prompt,
      "",
    ]),
  ]),
].join("\n");

// Written as Prettier would write them, so `pnpm format:check` and `--check` agree.
const formatted = async (path: string, source: string, parser: string) =>
  format(source, { ...(await resolveConfig(path)), parser });
const outputs: [string, string][] = [
  [
    `${dir}manifest.json`,
    await formatted(`${dir}manifest.json`, manifest, "json"),
  ],
  [`${dir}prompts.md`, await formatted(`${dir}prompts.md`, sheet, "markdown")],
];
if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, text]) => {
    try {
      return readFileSync(path, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([path]) => path).join(", ")}`);
    process.exit(1);
  }
} else for (const [path, text] of outputs) writeFileSync(path, text);
console.log(`${ART.length} assets`);
