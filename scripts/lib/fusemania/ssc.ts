/**
 * Fusemania charts as StepMania `.ssc` text, and the generated module that bundles them for the game.
 */
import { bpmRange, type Analysis } from "./analysis.js";
import { generateCharts, type Chart } from "./generate.js";
import type { SongSpec } from "./songs.js";

/** Rows per measure StepMania writes, smallest first. */
const ROW_COUNTS = [4, 8, 12, 16, 24, 32, 48, 64, 96, 192];

/** A chart's `#NOTES` body: measures of the fewest rows that hold their notes, separated by commas. */
export function noteData(chart: Chart, slotsPerBeat: number): string {
  const perMeasure = 4 * slotsPerBeat;
  // What each slot of the chart holds, one character per column.
  const cells = new Map<number, string[]>();
  const cell = (slot: number): string[] => {
    let row = cells.get(slot);
    if (!row) {
      row = ["0", "0", "0", "0"];
      cells.set(slot, row);
    }
    return row;
  };
  let last = 0;
  for (const note of chart.notes) {
    cell(note.slot)[note.column] =
      note.kind === "mine" ? "M" : note.kind === "hold" ? "2" : "1";
    last = Math.max(last, note.slot);
    if (note.kind === "hold" && note.endSlot !== undefined) {
      cell(note.endSlot)[note.column] = "3";
      last = Math.max(last, note.endSlot);
    }
  }
  const measures: string[] = [];
  for (let measure = 0; measure * perMeasure <= last; measure++) {
    const used: number[] = [];
    for (let slot = 0; slot < perMeasure; slot++)
      if (cells.has(measure * perMeasure + slot)) used.push(slot);
    const rows =
      ROW_COUNTS.find((count) =>
        used.every((slot) => (slot * count) % perMeasure === 0),
      ) ?? 192;
    const lines: string[] = [];
    for (let row = 0; row < rows; row++) {
      const at = (row * perMeasure) / rows;
      const found = Number.isInteger(at)
        ? cells.get(measure * perMeasure + at)
        : undefined;
      lines.push(found ? found.join("") : "0000");
    }
    measures.push(lines.join("\n"));
  }
  return measures.join("\n,\n");
}

const fixed = (value: number): string => value.toFixed(3);

/** The whole `.ssc` file of a song: its timing and its four charts. */
export function sscText(song: SongSpec, analysis: Analysis): string {
  const [low, high] = bpmRange(analysis);
  // A song whose tempo only wanders shows one number; one that really changes shows its range.
  const display =
    high - low < 3
      ? String(Math.round((low + high) / 2))
      : `${Math.round(low)}:${Math.round(high)}`;
  const lines = [
    "#VERSION:0.83;",
    `#TITLE:${song.title};`,
    "#SUBTITLE:;",
    `#ARTIST:${song.artist};`,
    "#CREDIT:Fusemania;",
    `#MUSIC:${song.audio.slice(song.audio.lastIndexOf("/") + 1)};`,
    `#OFFSET:${fixed(analysis.offset)};`,
    `#SAMPLESTART:${fixed(analysis.sample[0])};`,
    `#SAMPLELENGTH:${fixed(analysis.sample[1])};`,
    "#SELECTABLE:YES;",
    `#DISPLAYBPM:${display};`,
    `#BPMS:${analysis.bpms.map(([beat, bpm]) => `${fixed(beat)}=${fixed(bpm)}`).join(",")};`,
    "#STOPS:;",
  ];
  for (const chart of generateCharts(analysis))
    lines.push(
      "",
      "#NOTEDATA:;",
      "#STEPSTYPE:dance-single;",
      `#DESCRIPTION:${chart.difficulty};`,
      `#DIFFICULTY:${chart.difficulty};`,
      `#METER:${chart.meter};`,
      "#CREDIT:Fusemania;",
      `#NOTES:\n${noteData(chart, analysis.slotsPerBeat)}\n;`,
    );
  return `${lines.join("\n")}\n`;
}

/** `games/fusemania/src/engine/songs-data.ts`: every song's audio URL and `.ssc` text, sorted by title. */
export function songsDataModule(
  songs: readonly { song: SongSpec; ssc: string }[],
): string {
  const sorted = [...songs].sort((a, b) =>
    a.song.title.localeCompare(b.song.title, "en"),
  );
  const entries = sorted.map(
    ({ song, ssc }) =>
      `  {\n    id: ${JSON.stringify(song.id)},\n    audio: ${JSON.stringify(song.audio)},\n    ssc: ${JSON.stringify(ssc)},\n  },`,
  );
  return [
    "// Generated by scripts/fusemania-charts.ts from games/fusemania/charts/*.ssc. Do not edit: change a chart (or",
    "// the generator) and run `pnpm exec tsx scripts/fusemania-charts.ts bundle`.",
    "",
    "export interface SongData {",
    "  readonly id: string;",
    '  /** Site-relative URL of the audio, no leading slash, e.g. "music/arcade-adventure.m4a". */',
    "  readonly audio: string;",
    "  /** The .ssc file's text. */",
    "  readonly ssc: string;",
    "}",
    "",
    "export const SONGS_DATA: readonly SongData[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}
