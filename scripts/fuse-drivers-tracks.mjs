// Writes src/game/tracks-data.ts from tracks/*.tmj. The fold must parse a track with no file IO, so the
// maps travel as data in the bundle, identical on every peer. Run after editing a track in Tiled.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const GAME = "games/fuse-drivers";
const DIR = `${GAME}/tracks`;
const names = readdirSync(DIR)
  .filter((f) => f.endsWith(".tmj"))
  .map((f) => f.replace(".tmj", ""))
  .sort();
const entries = names.map(
  (n) =>
    `  ${JSON.stringify(n)}: ${readFileSync(`${DIR}/${n}.tmj`, "utf8").trim()},`,
);
writeFileSync(
  `${GAME}/src/game/tracks-data.ts`,
  `/* Generated by scripts-build-tracks.mjs from tracks/*.tmj. Do not edit by hand. */\n` +
    `export const TRACK_DATA: Record<string, unknown> = {\n${entries.join("\n")}\n};\n` +
    `export const TRACK_NAMES = ${JSON.stringify(names)} as const;\n`,
);
console.log(`wrote ${names.length} tracks`);
