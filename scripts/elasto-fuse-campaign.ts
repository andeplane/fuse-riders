/** Extract the canonical campaign from an original Elma.res (QOPEN.CPP / TOPOL.CPP loadbelso). */
import { readFileSync, writeFileSync } from "node:fs";

const data = readFileSync(process.argv[2]!);
const table = Buffer.from(data.subarray(4, 3604));
const signed = (n: number) => (n << 16) >> 16;
let a = 23,
  b = 9982;
for (let i = 0; i < table.length; i++) {
  table[i] = table[i]! ^ (a & 255);
  a %= 3391;
  b = signed(b + a * 3391);
  a = signed(31 * b + 3391);
}
const files = new Map<string, Buffer>();
const count = data.readInt32LE(0);
if (count < 54 || count > 150 || data.readInt32LE(3604) !== 1347839)
  throw new Error("Invalid resource header");
for (let i = 0; i < count; i++) {
  const at = i * 24;
  const name = table
    .subarray(at, at + 16)
    .toString("latin1")
    .split("\0")[0]!
    .toLowerCase();
  const size = table.readInt32LE(at + 16),
    offset = table.readInt32LE(at + 20);
  if (offset < 3608 || size < 0 || offset + size > data.length)
    throw new Error("Invalid resource entry");
  files.set(name, data.subarray(offset, offset + size));
}
// TOPOL.CPP Levelnevek, registered campaign order (54 levels).
const order =
  "a01 a02 a03 a04 a05 a06 a07 ujtag a08 a09 ujgrav a10 a11 a12 a13 a14 a15 a16 a17 ujupdown a18 a19 a20 a21 a22 a23 a24 a25 a26 ujkomb a27 ujtolcs a28 ujzuhan a29 a30 a31 a32 ujvissza a33 a34 a35 a36 a37 ujcsab mate a38 ujdownhi ujcsomo a39 a40 a41 ujhook a42".split(
    " ",
  );
const names = files
  .get("desclist.txt")!
  .toString("latin1")
  .trim()
  .split(/\r?\n/);
const levels = order.map((id, index) => {
  const raw = files.get(`${id}.leb`);
  if (!raw || raw.subarray(0, 5).toString() !== "@@^!@")
    throw new Error(`Missing level ${id}`);
  // The original getleveldescription() fixes this typo in DESCLIST.TXT too.
  const name = index === 30 ? "Animal Farm" : names[index]!;
  const polygonCount = Math.trunc(raw.readDoubleLE(130));
  const objectCount = Math.trunc(raw.readDoubleLE(138));
  if (
    polygonCount < 1 ||
    polygonCount > 300 ||
    objectCount < 1 ||
    objectCount > 64
  )
    throw new Error(`Invalid counts ${id}`);
  let at = 146;
  const polygons: { x: number; y: number }[][] = [];
  for (let p = 0; p < polygonCount; p++) {
    const grass = raw.readInt32LE(at),
      n = raw.readInt32LE(at + 4);
    at += 8;
    if (n < 3 || n > 5000) throw new Error(`Invalid polygon ${id}`);
    const points = Array.from({ length: n }, () => {
      const point = { x: raw.readDoubleLE(at), y: -raw.readDoubleLE(at + 8) };
      at += 16;
      return point;
    });
    if (!grass) polygons.push(points);
  }
  let start: { x: number; y: number } | undefined;
  const objects = [];
  for (let o = 0; o < objectCount; o++) {
    const x = raw.readDoubleLE(at),
      y = -raw.readDoubleLE(at + 8);
    const kind = raw.readInt32LE(at + 16),
      gravity = raw.readInt32LE(at + 20);
    at += 28;
    if (kind === 4) start = { x, y };
    else {
      if (kind < 1 || kind > 3 || gravity < 0 || gravity > 4)
        throw new Error(`Invalid object ${id}`);
      objects.push({
        kind: ["", "flower", "apple", "killer"][kind],
        x,
        y,
        ...(kind === 2 ? { gravity } : {}),
      });
    }
  }
  if (!start) throw new Error(`Missing start ${id}`);
  return { id: `elma-${id}`, name, polygons, start, faceLeft: true, objects };
});
writeFileSync(
  "games/elasto-fuse/src/engine/campaign-data.ts",
  `// Generated by scripts/elasto-fuse-campaign.ts from Elma.res; canonical internal campaign.\nimport type { Level } from "./level.js";\nexport const CAMPAIGN: readonly Level[] = ${JSON.stringify(levels)};\n`,
);
console.log(`Extracted ${levels.length} levels; first: ${levels[0]!.name}`);
